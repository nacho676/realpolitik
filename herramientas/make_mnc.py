def per_level(profit_b, hosts):
    """Weekly profit per level, in millions (3 decimals is plenty at this scale)."""
    levels = sum(hosts.values())
    return round(profit_b * 1000 / 52 / levels, 3)


def gen_effects():
    out = ["# Generated by herramientas/make_mnc.py. Do not edit by hand.", ""]
    out += ["mdr_mnc_start = {", "\tif = { limit = { NOT = { has_global_flag = mdr_mnc_started } }",
            "\t\tset_global_flag = mdr_mnc_started"]
    for cid, _name, hq, _sec, _p, hosts in COMPANIES:
        for tag, lv in hosts.items():
            assert tag != hq, (cid, tag)
            out += [f"\t\tif = {{ limit = {{ country_exists = {tag} }}",
                    f"\t\t\t{tag} = {{",
                    f"\t\t\t\tset_variable = {{ mdr_mnc_{cid} = {lv} }}",
                    f"\t\t\t\tadd_to_array = {{ global.mdr_mnc_{cid}_h = THIS }}",
                    "\t\t\t}", "\t\t}"]
    out += ["\t\tmdr_mnc_world_monthly = yes", "\t}", "}", ""]

    out += ["mdr_mnc_tick_all = {"] + [f"\tmdr_mnc_tick_{c[0]} = yes" for c in COMPANIES] + ["}", ""]

    for cid, _name, hq, sec, profit, hosts in COMPANIES:
        pw = per_level(profit, hosts)
        out += [f"mdr_mnc_tick_{cid} = {{",
                "\tset_temp_variable = { mdr_mnc_hq_sum = 0 }",
                "\tset_temp_variable = { mdr_mnc_hq_ok = 0 }",
                f"\tif = {{ limit = {{ country_exists = {hq} }}",
                f"\t\t{hq} = {{ save_event_target_as = mdr_mnc_hq }}",
                "\t\tset_temp_variable = { mdr_mnc_hq_ok = 1 }",
                "\t}",
                f"\tfor_each_scope_loop = {{ array = global.mdr_mnc_{cid}_h",
                f"\t\tset_temp_variable = {{ mdr_mnc_lv = mdr_mnc_{cid} }}",
                f"\t\tset_temp_variable = {{ mdr_mnc_frz = mdr_mnc_{cid}_frz }}",
                f"\t\tset_temp_variable = {{ mdr_mnc_nat = mdr_mnc_{cid}_nat }}",
                f"\t\tset_temp_variable = {{ mdr_mnc_pw = {pw} }}",
                f"\t\tset_temp_variable = {{ mdr_mnc_take = {SECTORS[sec]['take']} }}",
                f"\t\tset_temp_variable = {{ mdr_mnc_west = {1 if hq in WEST else 0} }}",
                "\t\tset_temp_variable = { mdr_mnc_hol = 0 }",
                f"\t\tif = {{ limit = {{ has_country_flag = mdr_mnc_{cid}_new }} set_temp_variable = {{ mdr_mnc_hol = 1 }} }}",
                "\t\tmdr_mnc_host_step = yes",
                f"\t\tset_variable = {{ mdr_mnc_{cid} = mdr_mnc_lv }}",
                f"\t\tset_variable = {{ mdr_mnc_{cid}_frz = mdr_mnc_frz }}",
                "\t\tif = { limit = { check_variable = { mdr_mnc_left = 1 } }",
                f"\t\t\tset_country_flag = {{ flag = mdr_mnc_{cid}_out days = 1825 value = 1 }}",
                "\t\t}",
                "\t}",
                "\tif = { limit = { check_variable = { mdr_mnc_hq_ok = 1 } check_variable = { mdr_mnc_hq_sum > 0 } }",
                "\t\tevent_target:mdr_mnc_hq = {",
                "\t\t\tif = { limit = { NOT = { has_variable = mdr_mnc_income_m } } set_variable = { mdr_mnc_income_m = 0 } }",
                "\t\t\tadd_to_variable = { mdr_mnc_income_m = mdr_mnc_hq_sum }",
                "\t\t}",
                "\t}",
                "}", ""]
    return "\n".join(out)


