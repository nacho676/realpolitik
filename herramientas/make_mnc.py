def main():
    (ROOT / "common/scripted_effects/mdr_mnc_gen.txt").write_text(gen_effects(), encoding="utf-8", newline="\n")
    (ROOT / "common/decisions/mdr_mnc_decisions.txt").write_text(gen_decisions(), encoding="utf-8", newline="\n")
    for lang in ("spanish", "english"):
        p = ROOT / f"localisation/{lang}/mdr_mnc_gen_l_{lang}.yml"
        p.write_text(gen_loc(lang), encoding="utf-8-sig", newline="\n")
    total = sum(len(c[5]) for c in COMPANIES)
    print(f"{len(COMPANIES)} companies, {total} host entries")


if __name__ == "__main__":
    main()
