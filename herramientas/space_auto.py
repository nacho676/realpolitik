def copy_md_window():
    # Copy of MD's Automation Settings window (interface/MD_automation_settings.gui, see COMPATIBILIDAD.md) with its four
    # page buttons narrower (130 px, our sprite), so the fifth, "Agencia espacial", fits in the same row.
    import re
    src = open("../Millennium-Dawn-2.0.0/interface/MD_automation_settings.gui", encoding="utf-8-sig").read()
    xs = {"20": 20, "190": 156, "360": 292, "530": 428}

    def narrow(m):
        block = m.group(0).replace('"GFX_sat_target_button"', '"GFX_mdr_auto_page_btn"')
        return re.sub(r"position = \{ x = (20|190|360|530) y = 518 \}", lambda p: f"position = {{ x = {xs[p.group(1)]} y = 518 }}", block)

    out, n = re.subn(r'buttonType = \{\s*name = "automation_\w+_page_button".*?\n\t\t\}', narrow, src, flags=re.S)
    assert n == 16, n
    with open("interface/MD_automation_settings.gui", "wb") as f:
        f.write(out.encode("utf-8"))


