def gfx():
    out = ["# Generated by herramientas/make_nuclear.py.", "spriteTypes = {"]
    for n in SINGLE:
        out.append(f'\tspriteType = {{ name = "GFX_mdr_wmd_{n}" textureFile = "{ART}{n}.dds" }}')
    for n in FRAMES2:
        out.append(f'\tspriteType = {{ name = "GFX_mdr_wmd_{n}" textureFile = "{ART}{n}.dds" noOfFrames = 2 effectFile = "gfx/FX/buttonstate.lua" }}')
    out.append(f'\tspriteType = {{ name = "GFX_mdr_wmd_digit" textureFile = "{ART}digit.dds" noOfFrames = 11 }}')
    # Round flags: the flag is shown through a circular mask, like the game's own masked flags.
    out.append(f'\tmaskedShieldType = {{ name = "GFX_mdr_wmd_flag_round" textureFile1 = "{ART}flag_ring.dds" textureFile2 = "{ART}flag_mask.tga" effectFile = "gfx/FX/maskedflag.lua" }}')
    # Toolbar button defined like Millennium Dawn's GFX_missile_button: 2 frames, no effect file.
    out.append(f'\tspriteType = {{ name = "GFX_mdr_wmd_topbar_button" textureFile = "{ART}topbar.dds" noOfFrames = 2 }}')
    out.append("}")
    return "\n".join(out) + "\n"


def txt(name, x, y, text, w, h=18, font="hoi_16mbs", fmt="left", tip=None):
    t = f' pdx_tooltip = "{tip}"' if tip else " alwaystransparent = yes"
    return (f'\t\tinstantTextboxType = {{ name = "{name}" position = {{ x = {x} y = {y} }} font = "{font}" borderSize = {{ x = 0 y = 0 }} '
            f'text = "{text}" maxWidth = {w} maxHeight = {h} fixedsize = yes format = {fmt}{t} }}')


def icon(name, x, y, sprite, extra=""):
    return f'\t\ticonType = {{ name = "{name}" spriteType = "GFX_mdr_wmd_{sprite}" position = {{ x = {x} y = {y} }}{extra} alwaystransparent = yes }}'


def btn(name, x, y, sprite, text=None, tip=None, font="hoi_16mbs"):
    t = f' buttonText = "{text}" buttonFont = "{font}"' if text else ""
    p = f' pdx_tooltip = "{tip}"' if tip else ""
    return f'\t\tbuttonType = {{ name = "{name}" position = {{ x = {x} y = {y} }} spriteType = "GFX_mdr_wmd_{sprite}"{t}{p} clicksound = click_default }}'


