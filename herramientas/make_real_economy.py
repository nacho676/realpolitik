"""Real 2000 economy: GDP and public debt for every country at game start.

Sources (saved in herramientas/datos_economia/):
  wb_gdp.json   World Bank NY.GDP.MKTP.PP.KD, GDP PPP in constant international dollars, year 2000
  wb_pc.json    World Bank NY.GDP.MKTP.PP.KD per capita, only to find Millennium Dawn's scale
  imf_debt.json IMF GGXWDG_NGDP, general government gross debt as % of GDP

Millennium Dawn measures GDP in billions of PPP dollars of an older base year: its starting gdp_per_capita
values are the World Bank figures times about 0.85. The scale factor is measured here (median of MD / World Bank)
so our targets stay on MD's scale and budgets keep their balance.

Writes common/scripted_effects/mdr_real_economy_gen.txt. Run:
    python herramientas/make_real_economy.py
"""
import json
import os
import re
import statistics
from pathlib import Path

MOD = Path(__file__).resolve().parent.parent
MD = MOD.parent / "Millennium-Dawn-2.0.3"
DATA = MOD / "herramientas" / "datos_economia"
OUT = MOD / "common" / "scripted_effects" / "mdr_real_economy_gen.txt"

# MD tag -> ISO3 where the names differ (only countries that existed in 2000)
ISO = {
    "BAH": "BHS", "BOS": "BIH", "BRM": "MMR", "BRU": "BRN", "CNG": "COG", "CUB": "CUB", "CZE": "CZE",
    "DJI": "DJI", "DRC": "COD", "EGY": "EGY", "ERI": "ERI", "FYR": "MKD", "GAM": "GMB", "HKG": "HKG",
    "HOL": "NLD", "KOR": "KOR", "KYR": "KGZ", "LAO": "LAO", "LIC": "LIE", "MAC": "MAC", "MNC": "MCO",
    "NAU": "NRU", "NKO": "PRK", "PAL": "PSE", "PER": "IRN", "SLO": "SVK", "SOM": "SOM", "SOV": "RUS",
    "SWA": "SWZ", "SYR": "SYR", "TAI": "TWN", "TIM": "TLS", "TRI": "TTO", "TUR": "TUR", "USA": "USA",
    "VEN": "VEN", "VER": "CPV", "YEM": "YEM", "MIC": "FSM",
}
# tags that share a name with a World Bank entry but are not that country in 2000
SKIP = {"SSU", "KOS", "PTR", "CAT", "SCO", "QUE", "TEX", "CAL", "FLA", "NYK", "HWI", "ASK", "WAS", "NIR"}


def wb_values(name):
    rows = json.loads((DATA / name).read_text(encoding="utf-8"))[1]
    return ({r["countryiso3code"]: r["value"] for r in rows if r["value"]},
            {r["country"]["value"].lower(): r["countryiso3code"] for r in rows})


def md_countries():
    out = {}
    for f in sorted(os.listdir(MD / "history" / "countries")):
        tag, name = f[:3], f[6:-4]
        text = (MD / "history" / "countries" / f).read_text(encoding="utf-8", errors="replace")
        pc = re.search(r"gdp_per_capita\s*=\s*([\d.]+)", text)
        out[tag] = (name, float(pc.group(1)) if pc else None)
    return out


def main():
    gdp, by_name = wb_values("wb_gdp.json")
    pc, _ = wb_values("wb_pc.json")
    imf = json.loads((DATA / "imf_debt.json").read_text(encoding="utf-8"))["values"]["GGXWDG_NGDP"]
    countries = md_countries()

    iso_of = {}
    for tag, (name, _) in countries.items():
        if tag in SKIP:
            continue
        iso = ISO.get(tag) or by_name.get(name.lower())
        if iso:
            iso_of[tag] = iso

    ratios = [mdpc / (pc[iso] / 1000) for tag, iso in iso_of.items()
              if (mdpc := countries[tag][1]) and iso in pc]
    scale = statistics.median(ratios)

    def debt_ratio(iso):
        years = imf.get(iso, {})
        for y in ("2000", "2001", "1999"):
            if y in years:
                return years[y]
        return None

    lines = [
        "# Generated by herramientas/make_real_economy.py - do not edit by hand.",
        f"# GDP: World Bank 2000 PPP x {scale:.3f} (Millennium Dawn's scale, measured on {len(ratios)} countries).",
        "# Debt: IMF general government gross debt, % of GDP, 2000.",
        "mdr_real_economy_targets = {",
    ]
    n_gdp = n_debt = 0
    for tag in sorted(iso_of):
        iso = iso_of[tag]
        body = []
        if iso in gdp:
            body.append(f"set_variable = {{ mdr_gdp_target = {gdp[iso] * scale / 1e9:.3f} }}")
            n_gdp += 1
        r = debt_ratio(iso)
        if r is not None:
            body.append(f"set_variable = {{ mdr_debt_ratio_2000 = {r:.1f} }}")
            n_debt += 1
        if body:
            lines.append(f"\tif = {{ limit = {{ country_exists = {tag} }} {tag} = {{ {' '.join(body)} }} }}"
                         f" # {countries[tag][0]} ({iso})")
    lines.append("}")
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    missing = sorted(t for t in iso_of if iso_of[t] not in gdp)
    print(f"scale {scale:.3f}; GDP for {n_gdp}, debt for {n_debt} countries")
    print("No World Bank GDP (MD's own GDP kept):", " ".join(missing))


if __name__ == "__main__":
    main()
