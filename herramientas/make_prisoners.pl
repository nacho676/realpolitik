	$gfx .= "\tprogressbartype = {\n\t\tname = \"GFX_mdr_pow_bar_$b->[0]\"\n\t\tcolor = { $b->[1] }\n\t\tcolortwo = { $b->[2] }\n\t\ttextureFile1 = \"gfx/interface/fuel_bar.dds\"\n\t\ttextureFile2 = \"gfx/interface/fuel_bar_bg.dds\"\n\t\tsize = { x = 204 y = 14 }\n\t\teffectFile = \"gfx/FX/progress_startend.lua\"\n\t}\n";
}
$gfx .= "}\n";
spew('interface/mdr_prisoner_faces.gfx', $gfx);

