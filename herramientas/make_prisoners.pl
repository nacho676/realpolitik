# Generates the captured generals system's slots and menu: common/scripted_effects/mdr_prisoners_slots.txt and _faces.txt,
# common/scripted_guis/mdr_prisoners_gui.txt, interface/mdr_prisoners.gui, interface/mdr_prisoner_faces.gfx,
# common/scripted_localisation/mdr_prisoners_rank_loc.txt and localisation/*/mdr_prisoners_rows_l_*.yml.
# Portraits and traits come from Millennium Dawn's common/characters. Run from the mod folder: perl herramientas/make_prisoners.pl
# Run it again after each Millennium Dawn update: new generals would show the unknown portrait.
use strict; use warnings;
my $N = 10;
my $MD = '../Millennium-Dawn-2.0.3';
sub spew { open my $f, '>:raw', $_[0] or die "$_[0]: $!"; print $f $_[1]; close $f }

# Generals of Millennium Dawn: character token -> portrait, and every trait they use.
my (@chars, %path_id, @paths, %traits);
for my $file (sort glob("$MD/common/characters/*.txt")) {
	open my $h, '<:raw', $file or next; local $/; my $t = <$h>; close $h;
	while ($t =~ /^\t(\w+)\s*=\s*\{(.*?)^\t\}/msg) {
		my ($name, $b) = ($1, $2);
		next unless $b =~ /\b(?:field_marshal|corps_commander)\s*=\s*\{(.*?)\n\t\t\}/s;
		my $mil = $1;
		if ($mil =~ /traits\s*=\s*\{([^}]*)\}/) { $traits{$_} = 1 for grep { /^\w+$/ } split ' ', $1 }
		next unless $b =~ /army\s*=\s*\{[^}]*?large\s*=\s*"([^"]+\.(?:dds|tga))"/is;
		my $p = $1;
		$path_id{$p} //= do { push @paths, $p; scalar @paths };
		push @chars, [$name, $path_id{$p}];
	}
}
# The game rejects these in is_character (error.log), so they show the unknown portrait.
my %invalid;
if (open my $h, '<', 'herramientas/pow_invalid_characters.txt') { while (<$h>) { chomp; $invalid{$_} = 1 } close $h }
@chars = grep { !$invalid{$_->[0]} } @chars;
my @trait_list = sort keys %traits;
my $F = scalar @paths;
print scalar(@chars), " generals, $F portraits, ", scalar(@trait_list), " traits\n";

# Portrait sprites use Millennium Dawn's own files. Frames 0 and -1 are the game's unknown officers.
